"""Generate the synthetic traces in traces/ (devices nobody on the team owns).
Unit IDs use the reserved pseudonym prefix bb a7.   python3 tools/synthetic-traces.py"""
import json
import os

LINK = "hid:046d:c547:2:ff00"
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "traces")


def frame(t, d, b):
    b = list(b) + [0] * ((7 if b[0] == 0x10 else 20) - len(b))
    return {"type": "frame", "t_ms": t, "link": LINK, "dir": d, "hex": " ".join(f"{x:02x}" for x in b)}


def receiver(flags):
    ex = [([0x10, 0xFF, 0x81, 0x00], [0x10, 0xFF, 0x81, 0x00] + flags)]
    if flags != [0x00, 0x09, 0x00]:
        # Only a non-read-only provider sends this write (enable notifications).
        ex.append(([0x10, 0xFF, 0x80, 0x00, 0x00, 0x09, 0x00], [0x10, 0xFF, 0x80, 0x00]))
    ex.append(([0x10, 0xFF, 0x83, 0xB5, 0x20], [0x11, 0xFF, 0x83, 0xB5, 0x20, 0x07, 0x08, 0x40, 0x80, 0x11, 0x00, 0x02]))
    ex.append(([0x10, 0xFF, 0x83, 0xB5, 0x30], [0x11, 0xFF, 0x83, 0xB5, 0x30, 0xBB, 0xA7, 0x00, 0x01]))
    name = list(b"AA MOUSE")
    ex.append(([0x10, 0xFF, 0x83, 0xB5, 0x40], [0x11, 0xFF, 0x83, 0xB5, 0x40, len(name)] + name))
    for n in range(1, 6):
        ex.append(([0x10, 0xFF, 0x83, 0xB5, 0x20 + n], [0x10, 0xFF, 0x8F, 0x83, 0xB5, 0x02]))
    return ex


def write(name, note, exchanges):
    header = {"type": "header", "battbar": "0.2.0", "link": LINK, "kind": "hidapi", "vendor_id": 0x046D,
              "product_id": 0xC547, "product": "USB Receiver", "bus": "usb", "collections": [[0xFF00, 1], [0xFF00, 2]]}
    lines, t = [{"type": "note", "text": note}, header], 0
    for out, inp in exchanges:
        lines.append(frame(t, "out", out)); t += 3
        lines.append(frame(t, "in", inp)); t += 3
    with open(os.path.join(ROOT, name), "w") as f:
        for line in lines:
            f.write(json.dumps(line, separators=(",", ":")) + "\n")


aa = receiver([0x00, 0x09, 0x00]) + [
    ([0x10, 0x01, 0x00, 0x1B, 0x00, 0x00, 0xAA], [0x11, 0x01, 0x00, 0x1B, 0x04, 0x02, 0xAA]),
    ([0x10, 0x01, 0x00, 0x0B, 0x00, 0x03], [0x11, 0x01, 0x00, 0x0B, 0x00]),
    ([0x10, 0x01, 0x00, 0x0B, 0x00, 0x05], [0x11, 0x01, 0x00, 0x0B, 0x00]),
    ([0x10, 0x01, 0x00, 0x0B, 0x10, 0x04], [0x11, 0x01, 0x00, 0x0B, 0x00]),
    ([0x10, 0x01, 0x00, 0x0B, 0x10, 0x01], [0x11, 0x01, 0x00, 0x0B, 0x06, 0x00, 0x03]),
    ([0x10, 0x01, 0x06, 0x0B], [0x11, 0x01, 0x06, 0x0B, 0x0B, 0x54, 0x00]),  # 2900 mV, on battery
]
write("synthetic-receiver-aa-battery-0x1001.jsonl",
      "Synthetic: Lightspeed receiver, HID++ 2.0 mouse on AA cells, 0x1001 reports 2900 mV (not Li-ion).", aa)

h10 = receiver([0x00, 0x00, 0x00]) + [
    ([0x10, 0x01, 0x00, 0x1B, 0x00, 0x00, 0xAA], [0x10, 0x01, 0x8F, 0x00, 0x1B, 0x01]),
    # HID++ 1.0 battery registers (GET_REGISTER): status 0x07, charge 0x0D (values made up).
    ([0x10, 0x01, 0x81, 0x07], [0x10, 0x01, 0x81, 0x07, 0x05, 0x00, 0x00]),
    ([0x10, 0x01, 0x81, 0x0D], [0x10, 0x01, 0x81, 0x0D, 0x32, 0x00, 0x00]),
]
write("synthetic-receiver-hidpp10-device.jsonl",
      "Synthetic: Lightspeed receiver, HID++ 1.0 device (ping answered with error 0x01), notification flags off, battery registers 0x07/0x0D.",
      h10)
