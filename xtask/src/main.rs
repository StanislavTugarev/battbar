//! `cargo xtask supported-devices [--check]` — generate docs/SUPPORTED_DEVICES.md from
//! the built-in device database (`--check`: fail if the file is out of date).

use battbar_core::devicedb::{DeviceDef, Protocol, ReceiverFamily};
use battbar_core::{DeviceDb, DeviceKind};
use std::path::PathBuf;

fn kind(k: DeviceKind) -> &'static str {
    match k {
        DeviceKind::Mouse => "Mouse",
        DeviceKind::Keyboard => "Keyboard",
        DeviceKind::Headset => "Headset",
        DeviceKind::Headphones => "Headphones",
        DeviceKind::Gamepad => "Gamepad",
        DeviceKind::Other => "Other",
    }
}

fn pids(v: &[u16]) -> String {
    v.iter().map(|p| format!("`{p:04X}`")).collect::<Vec<_>>().join(", ")
}

fn connections(d: &DeviceDef) -> String {
    let mut c = vec![];
    if !d.wpid.is_empty() {
        c.push(format!("Receiver (wpid {})", pids(&d.wpid)));
    }
    if !d.usb_pid.is_empty() {
        let what = if d.protocol == Protocol::Hidpp20 {
            "USB cable"
        } else {
            "Base station (USB)"
        };
        c.push(format!("{what} ({})", pids(&d.usb_pid)));
    }
    if !d.ble_pid.is_empty() {
        c.push(format!("Bluetooth LE ({})", pids(&d.ble_pid)));
    }
    if !d.bt_pid.is_empty() {
        c.push(format!("Bluetooth ({})", pids(&d.bt_pid)));
    }
    if !d.bt_name_patterns.is_empty() {
        c.push("Bluetooth (macOS battery)".into());
    }
    c.join("<br>")
}

/// "verified on: …" (checked by the maintainers), "reported by users", or nothing.
fn status(verified_on: &Option<String>, reported_by_users: bool) -> String {
    match (verified_on, reported_by_users) {
        (Some(v), _) => format!("verified on: {v}"),
        (None, true) => "reported by users".into(),
        (None, false) => String::new(),
    }
}

fn generate(db: &DeviceDb) -> String {
    let mut s = String::new();
    s += "<!-- Generated by `cargo xtask supported-devices` from devices/*.toml. Do not edit. -->\n\n";
    s += "# Supported devices\n\n";
    s += "battbar is not affiliated with or endorsed by any of the vendors below; names are used only to\n";
    s += "describe compatibility.\n\n";
    s += "## What works without being listed\n\n";
    s += "- **Logitech HID++ 2.0 devices** on a listed receiver, on a USB cable or over Bluetooth LE: name,\n";
    s += "  type and battery feature are read from the device itself. Listing a device adds its PIDs,\n";
    s += "  notes and (for voltage-only devices) a calibrated discharge curve.\n";
    s += "- **Any Bluetooth device whose battery macOS already knows**: Bluetooth LE devices with the\n";
    s += "  standard Battery Service, and classic Bluetooth audio devices (headphones, headsets).\n";
    s += "- **Other SteelSeries headsets** through the optional [`headsetcontrol`](https://github.com/Sapd/HeadsetControl) fallback, if it is installed.\n\n";
    s += "Something missing or wrong? See [ADDING_A_DEVICE.md](ADDING_A_DEVICE.md).\n\n";
    s += "## How changes are noticed\n\n";
    s += "Every device is read by the regular poll (every minute by default); that alone shows any\n";
    s += "supported device. Faster paths come on top and are only an acceleration:\n\n";
    s += "- USB devices, receivers and base stations appearing or disappearing: macOS hotplug\n";
    s += "  notifications (all devices). Without them, a re-scan every 5 minutes finds them.\n";
    s += "- Devices behind a receiver: connection notifications (0x41), the device's own messages and,\n";
    s += "  for devices that were disconnected, a ping every 2 s. A receiver that answers differently\n";
    s += "  is still read by the poll.\n";
    s += "- Headset changes on a base station: events sent by the base, only for models marked\n";
    s += "  below as reporting them; other bases are read by the poll.\n";
    s += "- Bluetooth: macOS connection notifications and HID hotplug.\n\n";
    s += "\"Verified on\" says where a device's behaviour (including these paths) was checked on real\n";
    s += "hardware; \"reported by users\" means users reported that it works.\n\n";

    s += "## Receivers\n\n| Receiver | Family | VID:PID | Status |\n|---|---|---|---|\n";
    let mut rs = db.receivers.clone();
    rs.sort_by_key(|r| (r.vendor_id, r.product_id));
    for r in &rs {
        let fam = match r.family {
            ReceiverFamily::Unifying => "Unifying",
            ReceiverFamily::Lightspeed => "Lightspeed",
            ReceiverFamily::Bolt => "Bolt (untested)",
        };
        s += &format!(
            "| {} | {fam} | `{:04X}:{:04X}` | {} |\n",
            r.name,
            r.vendor_id,
            r.product_id,
            status(&r.verified_on, false)
        );
    }

    for (title, proto) in [
        ("Logitech HID++ devices", Protocol::Hidpp20),
        ("SteelSeries headsets (native)", Protocol::SteelseriesNovaPro),
    ] {
        let mut ds: Vec<&DeviceDef> = db.devices.iter().filter(|d| d.protocol == proto).collect();
        ds.sort_by(|a, b| a.name.cmp(&b.name));
        s += &format!("\n## {title}\n\n| Device | Type | Connections | Notes | Status |\n|---|---|---|---|---|\n");
        for d in ds {
            let mut notes = d.notes.clone().unwrap_or_default();
            if d.base_events {
                notes += " Base reports headset changes itself (base events).";
            }
            s += &format!(
                "| {} | {} | {} | {} | {} |\n",
                d.name,
                kind(d.kind),
                connections(d),
                notes.trim(),
                status(&d.verified_on, d.reported_by_users)
            );
        }
    }
    s
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("supported-devices") => {
            let db = DeviceDb::embedded().expect("device database");
            let text = generate(&db);
            let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../docs/SUPPORTED_DEVICES.md");
            if args.iter().any(|a| a == "--check") {
                let current = std::fs::read_to_string(&path).unwrap_or_default();
                if current != text {
                    eprintln!("docs/SUPPORTED_DEVICES.md is out of date; run `cargo xtask supported-devices`");
                    std::process::exit(1);
                }
                println!("docs/SUPPORTED_DEVICES.md is up to date");
            } else {
                std::fs::write(&path, text).expect("write");
                println!("wrote {}", path.display());
            }
        }
        _ => {
            eprintln!("usage: cargo xtask supported-devices [--check]");
            std::process::exit(2);
        }
    }
}
